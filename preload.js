'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (name) => async (...args) => {
  const r = await ipcRenderer.invoke(name, ...args);
  if (!r.ok) throw new Error(r.error);
  return r.value;
};

contextBridge.exposeInMainWorld('cartridge', {
  state: call('state'),
  refresh: call('refresh'),
  install: call('install'),
  cancel: call('cancel'),
  uninstall: call('uninstall'),
  launch: call('launch'),
  addRoms: call('addRoms'),
  pickRoms: call('pickRoms'),
  removeRom: call('removeRom'),
  addRomFolder: call('addRomFolder'),
  removeRomFolder: call('removeRomFolder'),
  scanRomFolders: call('scanRomFolders'),
  onScanReport: (fn) => ipcRenderer.on('scanReport', (_e, r) => fn(r)),
  onScan: (fn) => ipcRenderer.on('scan', (_e, on) => fn(on)),
  assignRom: call('assignRom'),
  settings: call('settings'),
  checkAppUpdate: call('checkAppUpdate'),
  credits: call('credits'),
  romHelp: call('romHelp'),
  pickLibraryDir: call('pickLibraryDir'),
  pickBackground: call('pickBackground'),
  clearBackground: call('clearBackground'),
  openFolder: call('openFolder'),
  openPath: call('openPath'),
  reveal: call('reveal'),
  openUrl: call('openUrl'),
  openLog: call('openLog'),
  log: call('log'),
  copy: call('copy'),
  discover: call('discover'),
  addUserGame: call('addUserGame'),
  communityList: call('communityList'),
  addCommunityGame: call('addCommunityGame'),
  metascore: call('metascore'),
  cover: call('cover'),
  pickCover: call('pickCover'),
  setCoverFile: call('setCoverFile'),
  resetCover: call('resetCover'),
  findAllCovers: call('findAllCovers'),
  imageData: call('imageData'),
  onCoverProgress: (fn) => ipcRenderer.on('coverProgress', (_e, p) => fn(p)),
  listBackups: call('listBackups'),
  backupNow: call('backupNow'),
  backupAll: call('backupAll'),
  restoreBackup: call('restoreBackup'),
  openBackups: call('openBackups'),
  pickBackupDir: call('pickBackupDir'),
  onBackup: (fn) => ipcRenderer.on('backup', (_e, id, b) => fn(id, b)),
  steamStatus: call('steamStatus'),
  addToSteam: call('addToSteam'),
  removeFromSteam: call('removeFromSteam'),
  removeUserGame: call('removeUserGame'),
  pathForFile: (file) => webUtils.getPathForFile(file),
  onState: (fn) => ipcRenderer.on('state', (_e, s) => fn(s)),
  onJob: (fn) => ipcRenderer.on('job', (_e, id, job) => fn(id, job)),
});
